"""Validate the experiment registry and regenerate its index.

    python tools/index_experiments.py          # validate + write INDEX.md / index.json
    python tools/index_experiments.py --check  # validate only (CI); exit 1 on problems

Rules enforced (requirement sections 34-37):
* directory name = EXP-NNN-short-name, NNN unique (IDs are never reused);
* README.md has every required section;
* Status is one of PLANNED, RUNNING, SUPPORTED, FALSIFIED, INCONCLUSIVE, SUPERSEDED;
* config.json agrees with the README on id and status;
* an experiment that is not PLANNED has a results.csv;
* the Result section of a non-PLANNED experiment carries a taxonomy tag.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXP = ROOT / "experiments"
STATUSES = {"PLANNED", "RUNNING", "SUPPORTED", "FALSIFIED", "INCONCLUSIVE", "SUPERSEDED"}
SECTIONS = ["Research question", "Hypothesis", "Setup", "Commands", "Raw data", "Result",
            "Interpretation", "Limitations", "Status history"]
TAGS = ("[MEASURED", "[DERIVED", "[HYPOTHESIS", "[SUPPORTED", "[FALSIFIED", "[OPEN", "[LIMITATION")
NAME = re.compile(r"^EXP-(\d{3})-[a-z0-9]+(?:-[a-z0-9]+)*$")


def parse(d: Path):
    text = (d / "README.md").read_text(encoding="utf-8")
    title = text.splitlines()[0].split("—", 1)[-1].strip()
    field = dict(re.findall(r"^\| ([^|]+?) \| (.+?) \|$", text, re.M))
    status = field.get("Status", "").strip("* ")
    rqs = [x.strip() for x in field.get("Related questions", "").split(",") if x.strip().startswith("RQ")]
    sections = {m.group(1): m.start() for m in re.finditer(r"^## (.+)$", text, re.M)}
    result = ""
    if "Result" in sections:
        rest = text[sections["Result"]:]
        nxt = re.search(r"^## ", rest[3:], re.M)
        result = rest[: nxt.start() + 3] if nxt else rest
    return {"id": d.name, "title": title, "status": status, "rqs": rqs,
            "period": field.get("Period", ""), "sections": list(sections), "result": result,
            "has_results_csv": (d / "results.csv").exists()}


def main(check_only: bool) -> int:
    problems, rows, seen = [], [], {}
    others = sorted(p.name for p in EXP.iterdir() if p.is_dir() and not p.name.startswith("EXP-"))
    if others:
        # smoke tests and scratch runs are allowed here but are not registered
        # experiments: they never appear in the index and carry no claims
        print("note: unregistered run folders (not indexed): " + ", ".join(others))
    for d in sorted(p for p in EXP.iterdir() if p.is_dir() and p.name.startswith("EXP-")):
        m = NAME.match(d.name)
        if not m:
            problems.append(f"{d.name}: name must be EXP-NNN-short-name")
            continue
        if m.group(1) in seen:
            problems.append(f"{d.name}: number {m.group(1)} already used by {seen[m.group(1)]}")
        seen[m.group(1)] = d.name
        if not (d / "README.md").exists():
            problems.append(f"{d.name}: README.md missing")
            continue
        e = parse(d)
        for s in SECTIONS:
            if s not in e["sections"]:
                problems.append(f"{d.name}: section '{s}' missing")
        if e["status"] not in STATUSES:
            problems.append(f"{d.name}: status '{e['status']}' not in {sorted(STATUSES)}")
        cfg = d / "config.json"
        if cfg.exists():
            c = json.loads(cfg.read_text(encoding="utf-8"))
            if c.get("id") != d.name or c.get("status") != e["status"]:
                problems.append(f"{d.name}: config.json disagrees with README (id/status)")
        else:
            problems.append(f"{d.name}: config.json missing")
        if e["status"] != "PLANNED":
            if not e["has_results_csv"]:
                problems.append(f"{d.name}: {e['status']} without results.csv")
            if not any(t in e["result"] for t in TAGS):
                problems.append(f"{d.name}: Result section has no taxonomy tag")
        rows.append(e)
    if problems:
        print("\n".join("problem: " + p for p in problems))
    if check_only:
        return 1 if problems else 0
    index = [{k: e[k] for k in ("id", "title", "status", "rqs", "period")} for e in rows]
    (EXP / "index.json").write_text(json.dumps(index, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    counts = {s: sum(1 for e in rows if e["status"] == s) for s in sorted(STATUSES)}
    md = ["# Experiment index", "",
          "Generated by `python tools/index_experiments.py` from the experiment READMEs. "
          "Do not edit by hand. Machine-readable copy: [`index.json`](index.json).", "",
          "Status counts: " + ", ".join(f"{k} {v}" for k, v in counts.items() if v), "",
          "| ID | Title | Status | Questions | Period |", "|---|---|---|---|---|"]
    for e in rows:
        md.append(f"| [{e['id']}]({e['id']}/README.md) | {e['title']} | {e['status']} | "
                  f"{', '.join(e['rqs']) or '—'} | {e['period']} |")
    (EXP / "INDEX.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"{len(rows)} experiments indexed, {len(problems)} problems")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
